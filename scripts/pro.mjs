// Prepares the Pro registry, whose sources live in a private repository.
//
// The Pro items are not part of this repository. They are checked out (or
// downloaded) into registry/pro, which git ignores:
//
// - locally, clone the private repository there:
//     git clone git@github.com:Balick/balick-ui-pro.git registry/pro
// - on Vercel, set PRO_GITHUB_TOKEN (a read-only token for that repository)
//   and this script downloads it before the build.
//
// It then writes three generated modules, also ignored by git:
// - registry/__pro__.ts: the Pro items' metadata, used by the galleries, the
//   templates and the composer;
// - registry/__pro_blocks__.ts: their preview components, imported only by
//   registry/__index__.ts, so pages that list items do not load them;
// - registry/__pro_registry__.ts: the installable items with the content of
//   their files, imported only by the authenticated /r/pro route.
//
// Without the Pro sources the modules are empty, and the site builds with
// the free items only.
import { execFileSync } from "node:child_process"
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import path from "node:path"

const root = process.cwd()
const proDir = path.join(root, "registry/pro")
const manifestPath = path.join(proDir, "registry.json")
const repository = process.env.PRO_REPOSITORY || "Balick/balick-ui-pro"
const ref = process.env.PRO_REPOSITORY_REF || "main"
const token = process.env.PRO_GITHUB_TOKEN

const pascal = (name) =>
  name.split("-").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("")
const provided = new Set(["react", "react-dom", "next"])
const packageName = (specifier) =>
  specifier.split("/").slice(0, specifier.startsWith("@") ? 2 : 1).join("/")

async function download() {
  console.log(`pro: downloading ${repository}@${ref}`)
  const response = await fetch(`https://api.github.com/repos/${repository}/tarball/${ref}`, {
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: "application/vnd.github+json",
      "User-Agent": "balick-ui-build",
    },
  })
  if (!response.ok) {
    throw new Error(`pro: could not download ${repository}@${ref} (HTTP ${response.status})`)
  }
  const archive = path.join(root, ".pro-sources.tar.gz")
  writeFileSync(archive, Buffer.from(await response.arrayBuffer()))
  rmSync(proDir, { recursive: true, force: true })
  mkdirSync(proDir, { recursive: true })
  execFileSync("tar", ["-xzf", archive, "-C", proDir, "--strip-components=1"])
  rmSync(archive)
}

/** Checks the conventions scripts/check-blocks.mjs enforces for the free items. */
function check(items) {
  const errors = []
  for (const item of items) {
    const sources = item.files.map((file) => [file.path, readFileSync(path.join(root, file.path), "utf8")])
    if (item.type === "registry:block" && !new RegExp(`export function ${pascal(item.name)}\\b`).test(sources[0][1])) {
      errors.push(`${sources[0][0]} must export function ${pascal(item.name)}`)
    }
    const declared = new Set(item.dependencies ?? [])
    for (const [file, source] of sources) {
      for (const [, specifier] of source.matchAll(/from "([^"]+)"/g)) {
        if (specifier.startsWith("@/") || specifier.startsWith(".")) continue
        const pkg = packageName(specifier)
        if (!provided.has(pkg) && !declared.has(pkg)) {
          errors.push(`${file} imports ${pkg}, missing from ${item.name}'s dependencies`)
        }
      }
    }
  }
  if (errors.length) {
    console.error(errors.join("\n"))
    process.exit(1)
  }
}

/** The module path of a file, for an import: "registry/pro/blocks/x/x.tsx" → "@/registry/pro/blocks/x/x". */
const modulePath = (file) => `@/${file.replace(/\.tsx?$/, "")}`

function generate(items) {
  const header = "// Generated by scripts/pro.mjs. Do not edit.\n"
  const previewable = items.filter((item) => item.type === "registry:block" || item.type === "registry:example")
  const imports = previewable.map(
    (item) =>
      item.type === "registry:block"
        ? `import { ${pascal(item.name)} } from "${modulePath(item.files[0].path)}"`
        : `import ${pascal(item.name)} from "${modulePath(item.files[0].path)}"`
  )
  // Metadata only: the sources stay in __pro_registry__.ts.
  const metadata = items.map(({ files, ...item }) => ({
    ...item,
    files: files.map(({ path: file, type, target }) => ({ path: file, type, ...(target ? { target } : {}) })),
  }))
  const entries = (type) =>
    previewable
      .filter((item) => item.type === type)
      .map((item) => `  ${JSON.stringify(item.name)}: ${pascal(item.name)},`)
      .join("\n")

  writeFileSync(
    path.join(root, "registry/__pro__.ts"),
    `${header}// Metadata only: the components are in __pro_blocks__.ts.
export interface ProItem {
  name: string
  type: string
  title: string
  description: string
  categories?: string[]
  dependencies?: string[]
  registryDependencies?: string[]
  meta?: Record<string, unknown>
  files: { path: string; type: string; target?: string }[]
}

export const proItems: ProItem[] = ${JSON.stringify(metadata, null, 2)}
`
  )

  writeFileSync(
    path.join(root, "registry/__pro_blocks__.ts"),
    `${header}// The preview components of the Pro items: import it from registry/__index__.ts only.
import type * as React from "react"
${imports.join("\n")}

export const proBlocks: Record<string, React.ComponentType> = {
${entries("registry:block")}
}

export const proExamples: Record<string, React.ComponentType> = {
${entries("registry:example")}
}
`
  )

  // The installable items, in the format `shadcn build` writes.
  const built = Object.fromEntries(
    items
      .filter((item) => item.type !== "registry:example")
      .map((item) => [
        item.name,
        {
          $schema: "https://ui.shadcn.com/schema/registry-item.json",
          ...item,
          files: item.files.map((file) => ({
            ...file,
            content: readFileSync(path.join(root, file.path), "utf8"),
          })),
        },
      ])
  )
  writeFileSync(
    path.join(root, "registry/__pro_registry__.ts"),
    `${header}// Contains the sources of the Pro items: import it from the /r/pro route only.
export const proRegistry: Record<string, Record<string, unknown>> = ${JSON.stringify(built, null, 2)}
`
  )
}

if (!existsSync(manifestPath) && token) await download()

if (existsSync(manifestPath)) {
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"))
  check(manifest.items)
  generate(manifest.items)
  console.log(`pro: ${manifest.items.length} items from ${path.relative(root, manifestPath)}`)
} else {
  generate([])
  console.log("pro: no Pro sources, building the free items only")
}
